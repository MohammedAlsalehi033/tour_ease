class TravelBookingForm extends StatefulWidget {
  final String travelerId;

  const TravelBookingForm({
    Key? key,
    required this.travelerId,
  }) : super(key: key);

  @override
  State<TravelBookingForm> createState() => _TravelBookingFormState();
}

class _TravelBookingFormState extends State<TravelBookingForm> {
  // Form data model
  late TravelBookingModel bookingModel;

  // Controllers
  final TextEditingController pricePerSeatController = TextEditingController();

  // State variables for time and date
  Time startTime = Time(hour: 10, minute: 0);
  DateTime selectedDate = DateTime.now().add(const Duration(days: 1));
  String formattedDate = 'Any date';
  
  // Submission state
  bool isSubmitting = false;

  @override
  void initState() {
    super.initState();
    bookingModel = TravelBookingModel(
      travelerId: widget.travelerId,
      startLocationText: "",
      endLocationText: "",
      startLocationLat: 0.0,
      startLocationLng: 0.0,
      endLocationLat: 0.0,
      endLocationLng: 0.0,
      departureTime: DateTime.now().add(const Duration(days: 1)),
      seatsNeeded: 1,
      budget: 1000,
    );

    pricePerSeatController.text = bookingModel.budget.toString();
  }

  @override
  void dispose() {
    pricePerSeatController.dispose();
    super.dispose();
  }

  // Update booking model from ride filter state
  void _updateBookingModelFromFilterState(RideFilterState state) {
    setState(() {
      bookingModel.startLocationText = state.filterModel.pickupLocation;
      bookingModel.endLocationText = state.filterModel.destination;


        bookingModel.startLocationLat = state.filterModel.pickupLocationCoordinates.latitude;
        bookingModel.startLocationLng = state.filterModel.pickupLocationCoordinates.longitude;


        bookingModel.endLocationLat = state.filterModel.destinationCoordinates.latitude;
        bookingModel.endLocationLng = state.filterModel.destinationCoordinates.longitude;

    });
  }

  DateTime _combineDateAndTime(DateTime date, Time time) {
    return DateTime(
      date.year,
      date.month,
      date.day,
      time.hour,
      time.minute,
    );
  }

  void _submitForm(BuildContext context) {
    // Enhanced validation
    final String? validationError = _validateForm();
    if (validationError != null) {
      _showErrorSnackBar(context, validationError);
      return;
    }
    
    // Set submitting state
    setState(() {
      isSubmitting = true;
    });

    // Combine date and time
    final departureDateTime = _combineDateAndTime(selectedDate, startTime);
    bookingModel.departureTime = departureDateTime;

    // Create the ride listing with real user data
    final rideListing = RideListingModel(
      id: 0, // This will be generated by backend
      providerId: UserModel().id,
      startLocationText: bookingModel.startLocationText,
      endLocationText: bookingModel.endLocationText,
      startLocationLat: bookingModel.startLocationLat,
      startLocationLng: bookingModel.startLocationLng,
      endLocationLat: bookingModel.endLocationLat,
      endLocationLng: bookingModel.endLocationLng,
      departureTime: bookingModel.departureTime,
      pricePerSeat: double.tryParse(pricePerSeatController.text) ?? 0.0,
      seatsAvailable: bookingModel.seatsNeeded,
      luggage: bookingModel.luggageCount > 0 ? bookingModel.luggageCount : null,
      status: "active",
      mediaUrls: [],
      createdAt: DateTime.now(),
      provider: TransportationProviderModel(
        providerId: UserModel().id,
        licenseMmediaUrls: [],
        vehicleMediaUrls: [],
        vehicleType: "",
        seatsAvailable: bookingModel.seatsNeeded,
        accountStatus: "active",
        createdAt: DateTime.now(),
        user: UserModelTempForNow(
          id: UserModel().id,
          email: UserModel().email,
          username: UserModel().username.isNotEmpty ? UserModel().username : "Provider",
          mediaUrls: [],
          accountStatus: "active",
          createdAt: DateTime.now(),
        ),
      ),
    );

    // Submit to bloc
    context.read<TransporationProviderBloc>().add(
      CreateTransportationProviderListing(rideListing: rideListing),
    );
  }

  String? _validateForm() {
    if (bookingModel.startLocationText.isEmpty) {
      return 'Please select a pickup location';
    }
    
    if (bookingModel.endLocationText.isEmpty) {
      return 'Please select a destination';
    }
    
    if (bookingModel.startLocationText == bookingModel.endLocationText) {
      return 'Pickup location and destination cannot be the same';
    }
    
    if (pricePerSeatController.text.isEmpty) {
      return 'Please enter a price per seat';
    }
    
    final price = double.tryParse(pricePerSeatController.text);
    if (price == null || price <= 0) {
      return 'Please enter a valid price greater than 0';
    }
    
    if (price > 10000) {
      return 'Price seems too high. Please enter a reasonable amount';
    }
    
    if (bookingModel.seatsNeeded < 1) {
      return 'At least 1 seat must be available';
    }
    
    if (bookingModel.seatsNeeded > 8) {
      return 'Maximum 8 seats can be offered';
    }
    
    final departureDateTime = _combineDateAndTime(selectedDate, startTime);
    if (departureDateTime.isBefore(DateTime.now().add(Duration(hours: 1)))) {
      return 'Departure time must be at least 1 hour from now';
    }
    
    return null; // No validation errors
  }

  void _showErrorSnackBar(BuildContext context, String message) {
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Row(
          children: [
            Icon(Icons.error_outline, color: Colors.white),
            SizedBox(width: 12),
            Expanded(
              child: Text(
                message,
                style: TextStyle(fontWeight: FontWeight.w500),
              ),
            ),
          ],
        ),
        backgroundColor: Colors.red,
        duration: Duration(seconds: 4),
        behavior: SnackBarBehavior.floating,
        shape: RoundedRectangleBorder(
          borderRadius: BorderRadius.circular(8),
        ),
      ),
    );
  }

  void _showSuccessSnackBar(BuildContext context) {
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(
        content: Row(
          children: [
            Icon(Icons.check_circle_outline, color: Colors.white),
            SizedBox(width: 12),
            Text(
              'Ride listing created successfully!',
              style: TextStyle(fontWeight: FontWeight.w500),
            ),
          ],
        ),
        backgroundColor: Colors.green,
        duration: Duration(seconds: 3),
        behavior: SnackBarBehavior.floating,
        shape: RoundedRectangleBorder(
          borderRadius: BorderRadius.circular(8),
        ),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final colorScheme = theme.colorScheme;
    final textTheme = theme.textTheme;

    return BlocListener<TransporationProviderBloc, TransporationProviderState>(
      listener: (context, state) {
        if (state is TransportationProviderListingCreated) {
          setState(() {
            isSubmitting = false;
          });
          _showSuccessSnackBar(context);
          
          // Navigate back after successful creation
          Future.delayed(Duration(seconds: 2), () {
            Navigator.pop(context);
          });
        } else if (state is TransportationProviderdataError) {
          setState(() {
            isSubmitting = false;
          });
          _showErrorSnackBar(context, state.error);
        }
      },
      child: Padding(
        padding: EdgeInsets.symmetric(horizontal: 16.w),
        child: SingleChildScrollView(
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              SizedBox(height: 16.h),

              // Location selection section
              BlocConsumer<RideFilterBloc, RideFilterState>(
                listener: (context, state) {
                  _updateBookingModelFromFilterState(state);
                },
                builder: (context, state) {
                  return GestureDetector(
                    onTap: () => Navigator.push(
                      context,
                      MaterialPageRoute(builder: (context) => MapScreen()),
                    ),
                    child: Container(
                      padding: EdgeInsets.symmetric(horizontal: 16.w, vertical: 12.h),
                      decoration: BoxDecoration(
                        color: theme.colorScheme.surfaceVariant,
                        borderRadius: BorderRadius.circular(12.r),
                        border: Border.all(
                          color: theme.colorScheme.outline.withOpacity(0.3),
                          width: 1.5,
                        ),
                        boxShadow: [
                          BoxShadow(
                            color: Colors.black.withOpacity(0.05),
                            blurRadius: 4,
                            offset: Offset(0, 2),
                          ),
                        ],
                      ),
                      child: Column(
                        crossAxisAlignment: CrossAxisAlignment.start,
                        children: [
                          _buildSectionTitle('Where from?', theme),
                          Row(
                            children: [
                            Icon(Icons.location_on, color: theme.primaryColor, size: 20.sp),
                            SizedBox(width: 12.w),
                            Expanded(
                              child: Text(
                                state.filterModel.pickupLocation.isEmpty
                                    ? 'Select pickup location'
                                    : state.filterModel.pickupLocation,
                                style: TextStyle(
                                  fontSize: 16.sp,
                                  fontWeight: state.filterModel.pickupLocation.isEmpty
                                      ? FontWeight.normal
                                      : FontWeight.w600,
                                  color: state.filterModel.pickupLocation.isEmpty
                                      ? theme.hintColor
                                      : theme.textTheme.bodyMedium?.color,
                                ),
                              ),
                            ),
                          ],
                        ),
                        Divider(height: 24.h, thickness: 1),
                        _buildSectionTitle('Where to?', theme),
                        Row(
                          children: [
                            Icon(Icons.location_on, color: theme.primaryColor, size: 20.sp),
                            SizedBox(width: 12.w),
                            Expanded(
                              child: Text(
                                state.filterModel.destination.isEmpty
                                    ? 'Select destination'
                                    : state.filterModel.destination,
                                style: TextStyle(
                                  fontSize: 16.sp,
                                  fontWeight: state.filterModel.destination.isEmpty
                                      ? FontWeight.normal
                                      : FontWeight.w600,
                                  color: state.filterModel.destination.isEmpty
                                      ? theme.hintColor
                                      : theme.textTheme.bodyMedium?.color,
                                ),
                              ),
                            ),
                            Icon(Icons.arrow_forward_ios, color: theme.primaryColor, size: 16.sp),
                          ],
                        ),
                      ],
                    ),
                  ),
                );
              },
            ),
            SizedBox(height: 16.h),

            // Departure date section
            _buildSectionTitle('When?', theme),
            _buildSelectionTile(
              icon: Icons.calendar_today_outlined,
              title: formattedDate,
              onTap: () async {
                await showDialog(
                  context: context,
                  builder: (dialogContext) {
                    return Dialog(
                      shape: RoundedRectangleBorder(
                        borderRadius: BorderRadius.circular(16.r),
                      ),
                      child: SfDateRangePicker(
                        selectionMode: DateRangePickerSelectionMode.single,
                        initialSelectedDate: selectedDate,
                        minDate: DateTime.now(),
                        maxDate: DateTime.now().add(const Duration(days: 90)),
                        onSelectionChanged: (DateRangePickerSelectionChangedArgs args) {
                          if (args.value is DateTime) {
                            final newDate = args.value as DateTime;
                            final combinedDateTime = _combineDateAndTime(newDate, startTime);
                            
                            // Check if the combined date and time is in the past
                            if (combinedDateTime.isBefore(DateTime.now())) {
                              Navigator.pop(dialogContext);
                              ScaffoldMessenger.of(context).showSnackBar(
                                SnackBar(
                                  content: Row(
                                    children: [
                                      Icon(Icons.warning_amber_rounded, color: Colors.white),
                                      SizedBox(width: 12),
                                      Expanded(
                                        child: Text(
                                          'The selected date with current time (${startTime.format(context)}) is in the past. Please adjust the time.',
                                          style: TextStyle(fontWeight: FontWeight.w500),
                                        ),
                                      ),
                                    ],
                                  ),
                                  backgroundColor: Colors.orange,
                                  duration: Duration(seconds: 4),
                                  behavior: SnackBarBehavior.floating,
                                ),
                              );
                              // Still allow the date to be set, but warn the user
                            }
                            
                            setState(() {
                              selectedDate = newDate;
                              formattedDate = DateFormat('EEE, MMM d, yyyy').format(selectedDate);
                              bookingModel.departureTime = _combineDateAndTime(
                                  selectedDate,
                                  startTime
                              );
                            });
                            
                            if (!combinedDateTime.isBefore(DateTime.now())) {
                              Navigator.pop(dialogContext);
                            }
                          }
                        },
                        headerStyle: DateRangePickerHeaderStyle(
                          textStyle: textTheme.titleMedium?.copyWith(
                            color: colorScheme.onSurface,
                          ),
                        ),
                        monthCellStyle: DateRangePickerMonthCellStyle(
                          todayTextStyle: TextStyle(
                            color: colorScheme.onSurface,
                            fontWeight: FontWeight.w600,
                          ),
                          todayCellDecoration: BoxDecoration(
                            color: colorScheme.surfaceVariant,
                            shape: BoxShape.circle,
                          ),
                        ),
                        selectionColor: colorScheme.primary,
                      ),
                    );
                  },
                );
              },
              theme: theme,
            ),

            SizedBox(height: 16.h),

            // Time section
            _buildSectionTitle('Preferred Time', theme),
            _buildSelectionTile(
              icon: Icons.access_time,
              title: startTime.format(context),
              onTap: () async {
                Navigator.of(context).push(
                  showPicker(
                    themeData: Theme.of(context),
                    context: context,
                    value: startTime,
                    sunrise: TimeOfDay(hour: 6, minute: 0),
                    sunset: TimeOfDay(hour: 18, minute: 0),
                    duskSpanInMinutes: 120,
                    onChange: (newTime) {
                      // Validate if selected time is in the past
                      final combinedDateTime = _combineDateAndTime(selectedDate, newTime);
                      if (combinedDateTime.isBefore(DateTime.now())) {
                        ScaffoldMessenger.of(context).showSnackBar(
                          SnackBar(
                            content: Row(
                              children: [
                                Icon(Icons.error_outline, color: Colors.white),
                                SizedBox(width: 12),
                                Expanded(
                                  child: Text(
                                    'Cannot select a time in the past. Please choose a future time.',
                                    style: TextStyle(fontWeight: FontWeight.w500),
                                  ),
                                ),
                              ],
                            ),
                            backgroundColor: Colors.red,
                            duration: Duration(seconds: 3),
                            behavior: SnackBarBehavior.floating,
                          ),
                        );
                        return;
                      }
                      
                      setState(() {
                        startTime = newTime;
                        bookingModel.departureTime = _combineDateAndTime(
                            selectedDate,
                            startTime
                        );
                      });
                    },
                  ),
                );
              },
              theme: theme,
            ),

            SizedBox(height: 16.h),

            // Seats section
            _buildSectionTitle('How many seats?', theme),
            _buildCounterTile(
              title: 'Available Seats',
              value: bookingModel.seatsNeeded,
              onDecrease: () {
                if (bookingModel.seatsNeeded > 1) {
                  setState(() {
                    bookingModel.seatsNeeded--;
                  });
                }
              },
              onIncrease: () {
                setState(() {
                  bookingModel.seatsNeeded++;
                });
              },
              theme: theme,
            ),

            SizedBox(height: 16.h),

            // Luggage section
            _buildSectionTitle('Luggage', theme),
            _buildCounterTile(
              title: 'Pieces of Luggage',
              value: bookingModel.luggageCount,
              onDecrease: () {
                if (bookingModel.luggageCount > 0) {
                  setState(() {
                    bookingModel.luggageCount--;
                  });
                }
              },
              onIncrease: () {
                if (bookingModel.luggageCount < 20) {
                  setState(() {
                    bookingModel.luggageCount++;
                  });
                }
              },
              theme: theme,
              minValue: 0,
              maxValue: 20,
            ),

            SizedBox(height: 16.h),

            // Price section
            _buildSectionTitle('Price per person (PKR)', theme),
            Container(
              decoration: BoxDecoration(
                color: theme.colorScheme.surfaceVariant,
                borderRadius: BorderRadius.circular(12.r),
                border: Border.all(
                  color: theme.colorScheme.outline.withOpacity(0.3),
                  width: 1.5,
                ),
                boxShadow: [
                  BoxShadow(
                    color: Colors.black.withOpacity(0.05),
                    blurRadius: 4,
                    offset: Offset(0, 2),
                  ),
                ],
              ),
              child: TextField(
                controller: pricePerSeatController,
                keyboardType: TextInputType.number,
                decoration: InputDecoration(
                  suffixText: 'PKR',
                  suffixStyle: theme.textTheme.bodyMedium?.copyWith(
                    fontWeight: FontWeight.w500,
                    color: theme.colorScheme.onSurface,
                  ),
                  hintText: 'Enter price per seat in PKR',
                  hintStyle: theme.textTheme.bodyMedium?.copyWith(
                    color: theme.colorScheme.onSurface.withOpacity(0.5),
                  ),
                  prefixIcon: Icon(
                    Icons.attach_money,
                    color: theme.colorScheme.primary,
                    size: 20.sp,
                  ),
                  contentPadding: EdgeInsets.symmetric(
                    horizontal: 16.w,
                    vertical: 14.h,
                  ),
                  border: InputBorder.none,
                ),
                onChanged: (value) {
                  setState(() {
                    bookingModel.budget = int.tryParse(value) ?? 0;
                  });
                },
              ),
            ),

            SizedBox(height: 32.h),

            // Submit button
            SizedBox(
              width: double.infinity,
              child: ElevatedButton.icon(
                onPressed: isSubmitting ? null : () => _submitForm(context),
                icon: isSubmitting 
                  ? SizedBox(
                      width: 20.sp,
                      height: 20.sp,
                      child: CircularProgressIndicator(
                        strokeWidth: 2,
                        valueColor: AlwaysStoppedAnimation<Color>(Colors.white),
                      ),
                    )
                  : Icon(Icons.check_circle, size: 20.sp),
                label: Text(
                  isSubmitting ? 'Creating...' : 'Create Ride Listing',
                  style: theme.textTheme.labelLarge?.copyWith(
                    color: Colors.white,
                    fontWeight: FontWeight.bold,
                  ),
                ),
                style: ElevatedButton.styleFrom(
                  backgroundColor: theme.colorScheme.primary,
                  foregroundColor: Colors.white,
                  padding: EdgeInsets.symmetric(vertical: 16.h),
                  shape: RoundedRectangleBorder(
                    borderRadius: BorderRadius.circular(12.r),
                  ),
                  elevation: 2,
                ),
              ),
            ),
            SizedBox(height: 16.h),
          ],
        ),
      ),
    ),
    );
  }

  // Helper widget methods
  Widget _buildSectionTitle(String title, ThemeData theme) {
    return Padding(
      padding: EdgeInsets.only(bottom: 8.h),
      child: Text(
        title,
        style: theme.textTheme.titleMedium?.copyWith(
          color: theme.colorScheme.primary,
        ),
      ),
    );
  }

  Widget _buildSelectionTile({
    required IconData icon,
    required String title,
    required VoidCallback onTap,
    required ThemeData theme,
  }) {
    return InkWell(
      onTap: onTap,
      borderRadius: BorderRadius.circular(12.r),
      child: Container(
        padding: EdgeInsets.symmetric(horizontal: 16.w, vertical: 14.h),
        decoration: BoxDecoration(
          color: theme.colorScheme.surfaceVariant,
          borderRadius: BorderRadius.circular(12.r),
          border: Border.all(
            color: theme.colorScheme.outline.withOpacity(0.3),
            width: 1.5,
          ),
          boxShadow: [
            BoxShadow(
              color: Colors.black.withOpacity(0.05),
              blurRadius: 4,
              offset: Offset(0, 2),
            ),
          ],
        ),
        child: Row(
          children: [
            Icon(
              icon,
              size: 20.sp,
              color: theme.colorScheme.primary,
            ),
            SizedBox(width: 12.w),
            Expanded(
              child: Text(
                title,
                style: theme.textTheme.bodyLarge?.copyWith(
                  fontWeight: FontWeight.w600,
                  color: title.contains('Select') || title.contains('Any')
                      ? theme.colorScheme.onSurface.withOpacity(0.5)
                      : theme.colorScheme.onSurface,
                ),
              ),
            ),
            Icon(
              Icons.chevron_right,
              size: 20.sp,
              color: theme.colorScheme.onSurfaceVariant,
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildCounterTile({
    required String title,
    required int value,
    required VoidCallback onDecrease,
    required VoidCallback onIncrease,
    required ThemeData theme,
    int minValue = 1,
    int maxValue = 100,
  }) {
    return Container(
      padding: EdgeInsets.symmetric(horizontal: 16.w, vertical: 14.h),
      decoration: BoxDecoration(
        color: theme.colorScheme.surfaceVariant,
        borderRadius: BorderRadius.circular(12.r),
        border: Border.all(
          color: theme.colorScheme.outline.withOpacity(0.3),
          width: 1.5,
        ),
        boxShadow: [
          BoxShadow(
            color: Colors.black.withOpacity(0.05),
            blurRadius: 4,
            offset: Offset(0, 2),
          ),
        ],
      ),
      child: Row(
        mainAxisAlignment: MainAxisAlignment.spaceBetween,
        children: [
          Text(
            title,
            style: theme.textTheme.bodyLarge?.copyWith(
              fontWeight: FontWeight.w600,
              color: theme.colorScheme.onSurface,
            ),
          ),
          Row(
            children: [
              _buildCircleButton(
                icon: Icons.remove,
                onTap: onDecrease,
                enabled: value > minValue,
                theme: theme,
              ),
              SizedBox(width: 16.w),
              Text(
                '$value',
                style: theme.textTheme.headlineSmall?.copyWith(
                  fontWeight: FontWeight.bold,
                  color: theme.colorScheme.primary,
                ),
              ),
              SizedBox(width: 16.w),
              _buildCircleButton(
                icon: Icons.add,
                onTap: onIncrease,
                enabled: value < maxValue,
                theme: theme,
              ),
            ],
          ),
        ],
      ),
    );
  }

  Widget _buildCircleButton({
    required IconData icon,
    required VoidCallback onTap,
    required bool enabled,
    required ThemeData theme,
  }) {
    return InkWell(
      onTap: enabled ? onTap : null,
      borderRadius: BorderRadius.circular(20.r),
      child: Container(
        width: 36.w,
        height: 36.h,
        decoration: BoxDecoration(
          color: enabled 
              ? theme.colorScheme.primary.withOpacity(0.1) 
              : theme.colorScheme.surfaceVariant,
          shape: BoxShape.circle,
          border: Border.all(
            color: enabled ? theme.colorScheme.primary : theme.colorScheme.outline.withOpacity(0.3),
            width: 1.5,
          ),
        ),
        child: Icon(
          icon,
          size: 18.sp,
          color: enabled ? theme.colorScheme.primary : theme.colorScheme.onSurfaceVariant.withOpacity(0.4),
        ),
      ),
    );
  }
}

// Data model class
class TravelBookingModel {
  String travelerId;
  String startLocationText;
  String endLocationText;
  double startLocationLat;
  double startLocationLng;
  double endLocationLat;
  double endLocationLng;
  DateTime departureTime;
  int seatsNeeded;
  int budget;
  int luggageCount;

  TravelBookingModel({
    required this.travelerId,
    required this.startLocationText,
    required this.endLocationText,
    required this.startLocationLat,
    required this.startLocationLng,
    required this.endLocationLat,
    required this.endLocationLng,
    required this.departureTime,
    required this.seatsNeeded,
    required this.budget,
    this.luggageCount = 0,
  });

  Map<String, dynamic> toJson() {
    return {
      'travelerId': travelerId,
      'startLocationText': startLocationText,
      'endLocationText': endLocationText,
      'startLocationLat': startLocationLat,
      'startLocationLng': startLocationLng,
      'endLocationLat': endLocationLat,
      'endLocationLng': endLocationLng,
      'departureTime': departureTime.toIso8601String(),
      'seatsNeeded': seatsNeeded,
      'budget': budget,
      'luggageCount': luggageCount,
    };
  }
}